#!/usr/bin/env bash
# Fixture repositories prove each length limit at its boundary and that only
# the generated header in the first five lines exempts sqlc output.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
WORK=$(mktemp -d "${TMPDIR:-/tmp}/aboutme-check-lengths.XXXXXX")
trap 'rm -rf -- "$WORK"' EXIT
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE

fail() { printf 'check-lengths-test: %s\n' "$*" >&2; exit 1; }

HEADER='// Code generated by sqlc. DO NOT EDIT.'
REPO=$WORK/repo

fresh_repo() {
  rm -rf -- "$REPO"
  mkdir -p "$REPO/scripts"
  cp "$ROOT/scripts/check-lengths.sh" "$REPO/scripts/"
  git init -q "$REPO"
}

# lines_file <path> <lines> [header-line]: writes and tracks <lines> lines,
# with the header on [header-line] when given.
lines_file() {
  local path=$1 lines=$2 header=${3:-0} i
  mkdir -p "$(dirname "$REPO/$path")"
  for ((i = 1; i <= lines; i++)); do
    if ((i == header)); then
      printf '%s\n' "$HEADER"
    else
      printf 'line %d\n' "$i"
    fi
  done >"$REPO/$path"
  git -C "$REPO" add -- "$path"
}

expect_pass() {
  local status=0
  bash "$REPO/scripts/check-lengths.sh" >"$WORK/output" 2>&1 || status=$?
  ((status == 0)) || fail "$1: expected pass, got $status: $(cat "$WORK/output")"
  grep -q '^check-lengths: ok ' "$WORK/output" || fail "$1: no ok line"
}

# expect_fail <case> <path> <lines> <max>
expect_fail() {
  local status=0
  bash "$REPO/scripts/check-lengths.sh" >"$WORK/output" 2>&1 || status=$?
  ((status == 1)) || fail "$1: expected exit 1, got $status: $(cat "$WORK/output")"
  grep -Fqx "too long: $2 has $3 lines (max $4)" "$WORK/output" ||
    fail "$1: missing violation: $(cat "$WORK/output")"
  grep -Fqx 'check-lengths: 1 file(s) over the limit' "$WORK/output" ||
    fail "$1: expected exactly one violation: $(cat "$WORK/output")"
}

fresh_repo
lines_file apps/server/internal/store/queries.sql.go 900 1
lines_file apps/server/internal/store/querier.go 800 1
expect_pass 'header-bearing sqlc output'

fresh_repo
lines_file apps/server/internal/store/custom.sql.go 601
expect_fail 'handwritten .sql.go' apps/server/internal/store/custom.sql.go 601 600

fresh_repo
lines_file apps/server/internal/store/late.sql.go 601 6
expect_fail 'header after line five' apps/server/internal/store/late.sql.go 601 600

fresh_repo
lines_file apps/server/internal/foo/foo.go 600
expect_pass 'server Go at 600'

fresh_repo
lines_file apps/server/internal/foo/foo.go 601
expect_fail 'server Go at 601' apps/server/internal/foo/foo.go 601 600

fresh_repo
lines_file apps/server/internal/foo/foo_test.go 800
lines_file apps/server/internal/foo/testdata/fixture.go 800
expect_pass 'server tests'

fresh_repo
lines_file deploy/observer/internal/foo/foo.go 650
lines_file apps/web/app/foo.ts 650
lines_file scripts/foo.sh 700
expect_pass 'code outside apps/server at 650 and 700'

fresh_repo
lines_file deploy/observer/internal/foo/foo.go 701
expect_fail 'code outside apps/server at 701' deploy/observer/internal/foo/foo.go 701 700

fresh_repo
lines_file docs/foo.md 450
expect_pass 'Markdown at 450'

fresh_repo
lines_file docs/foo.md 451
expect_fail 'Markdown at 451' docs/foo.md 451 450

printf 'check-lengths-test: passed\n'
